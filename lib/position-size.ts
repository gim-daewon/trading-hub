/**
 * 포지션 크기 계산(2026-10-27). 사용자가 공유한 원칙: 한 번에 감당할 위험(1R)을 시드의 1%(최대 1.5%)로 정하고,
 * 손절폭으로 크기를 거꾸로 구한다. 안전은 레버리지 배수가 아니라 손절까지 잃는 돈이 정한다.
 * 수수료를 넣으면 손절까지 잃는 돈(수수료 포함)이 정확히 1R이 되게 크기를 줄인다 — 글의 계산에는 수수료가 빠져 있었다.
 */

/** 기준 — 사용자 공유 원칙(1R 권장 1%, 최대 1.5%)과 경고 문턱 */
export const 크기기준 = {
  권장위험퍼: 1,
  최대위험퍼: 1.5,
  /** 이보다 레버리지가 크면 청산가가 손절가보다 가까워질 수 있어 확인하라고 알린다 */
  레버리지경고: 3,
  /** 손절폭이 진입가의 이 비율(%)보다 좁으면 수수료·밀림이 R을 크게 갉아먹는다 */
  좁은손절퍼: 0.2,
  /** 바이낸스 선물 시장가 기본 수수료(한쪽 %) — 등급·할인에 따라 다르니 화면에서 바꿀 수 있다 */
  기본수수료퍼: 0.05,
}

export interface 크기입력 { 시드: number; 위험퍼: number; 진입: number; 손절: number; 수수료퍼: number; 목표R: number }
export interface 크기결과 {
  방향: '롱' | '숏'
  위험금액: number; 손절폭: number; 수량: number; 포지션금액: number; 레버리지: number
  손절시손실: number; 왕복수수료: number
  목표가: number; 목표순이익: number; 목표실제R: number
  경고: string[]
}

export function 포지션계산(x: 크기입력): 크기결과 {
  for (const [k, v] of Object.entries(x)) if (!Number.isFinite(v)) throw new Error(`${k}가 숫자가 아니다`)
  if (x.시드 <= 0 || x.진입 <= 0 || x.손절 <= 0) throw new Error('시드·진입가·손절가는 0보다 커야 한다')
  if (x.위험퍼 <= 0 || x.수수료퍼 < 0 || x.목표R <= 0) throw new Error('위험%·목표R은 0보다 크고 수수료는 0 이상')
  if (x.진입 === x.손절) throw new Error('진입가와 손절가가 같다')

  const 방향 = x.손절 < x.진입 ? '롱' : '숏'
  const 수수료 = x.수수료퍼 / 100
  const 위험금액 = x.시드 * x.위험퍼 / 100
  const 손절폭 = Math.abs(x.진입 - x.손절)
  // 1개당 손절 손실 = 가격 차 + 진입·청산 수수료
  const 개당손실 = 손절폭 + 수수료 * (x.진입 + x.손절)
  const 수량 = 위험금액 / 개당손실
  const 포지션금액 = 수량 * x.진입
  const 목표가 = 방향 === '롱' ? x.진입 + x.목표R * 손절폭 : x.진입 - x.목표R * 손절폭
  const 목표순이익 = 수량 * x.목표R * 손절폭 - 수량 * 수수료 * (x.진입 + 목표가)

  const 경고: string[] = []
  if (x.위험퍼 > 크기기준.최대위험퍼) 경고.push(`위험 ${x.위험퍼}%는 최대 ${크기기준.최대위험퍼}%를 넘는다 — 연패 몇 번이면 회복이 어렵다`)
  const 레버리지 = 포지션금액 / x.시드
  if (레버리지 > 크기기준.레버리지경고) 경고.push(`레버리지 ${레버리지.toFixed(1)}배 — 청산가가 손절가보다 먼저 오지 않는지 거래소에서 확인`)
  if (손절폭 / x.진입 * 100 < 크기기준.좁은손절퍼) 경고.push(`손절폭 ${(손절폭 / x.진입 * 100).toFixed(2)}%로 좁다 — 수수료·밀림이 R을 크게 줄인다`)
  if (방향 === '숏' && x.목표R * 손절폭 >= x.진입) 경고.push('목표가가 0 이하 — 목표 R을 줄인다')

  return {
    방향, 위험금액, 손절폭, 수량, 포지션금액, 레버리지,
    손절시손실: 수량 * 개당손실, 왕복수수료: 수량 * 수수료 * (x.진입 + x.손절),
    목표가, 목표순이익, 목표실제R: 목표순이익 / 위험금액, 경고,
  }
}
