import { test } from 'node:test'
import assert from 'node:assert/strict'
import { 포지션계산 } from './position-size.ts'

// 2026-10-27 사용자가 공유한 원칙: 시드 1만 달러, 1R = 시드의 1%(최대 1.5%), 손절폭으로 크기를 정한다
const 가깝다 = (a: number, b: number, 오차 = 1e-3) => assert.ok(Math.abs(a - b) <= 오차, `${a} ≠ ${b}`)

test('글의 예시: 1만 달러 · 1.5% · 진입 82,000 · 손절 81,000 · 수수료 0 → 0.15 BTC, 3R은 450달러', () => {
  const r = 포지션계산({ 시드: 10000, 위험퍼: 1.5, 진입: 82000, 손절: 81000, 수수료퍼: 0, 목표R: 3 })
  assert.equal(r.방향, '롱')
  가깝다(r.위험금액, 150)
  가깝다(r.수량, 0.15)
  가깝다(r.포지션금액, 12300)
  가깝다(r.레버리지, 1.23)
  가깝다(r.목표가, 85000)
  가깝다(r.목표순이익, 450)
  가깝다(r.목표실제R, 3)
})

test('수수료를 넣으면 손절까지 잃는 돈이 그대로 1R이 되게 크기가 줄고, 3R 목표의 실제 R도 줄어든다', () => {
  const r = 포지션계산({ 시드: 10000, 위험퍼: 1.5, 진입: 82000, 손절: 81000, 수수료퍼: 0.05, 목표R: 3 })
  // 1개당 손실 = 1,000 + 0.0005×(82,000+81,000) = 1,081.5
  가깝다(r.수량, 150 / 1081.5, 1e-6)
  가깝다(r.손절시손실, 150, 1e-6)
  assert.ok(r.목표실제R < 3 && r.목표실제R > 2.6)
  assert.ok(r.왕복수수료 > 10 && r.왕복수수료 < 13)
})

test('숏: 손절이 진입보다 위면 숏, 목표가는 아래로', () => {
  const r = 포지션계산({ 시드: 10000, 위험퍼: 1, 진입: 82000, 손절: 83000, 수수료퍼: 0, 목표R: 2 })
  assert.equal(r.방향, '숏')
  가깝다(r.수량, 0.1)
  가깝다(r.목표가, 80000)
})

test('경고: 위험 1.5% 넘음 · 레버리지 3배 넘음 · 손절폭 0.2% 미만 · 진입=손절은 계산 안 함', () => {
  assert.ok(포지션계산({ 시드: 10000, 위험퍼: 3, 진입: 82000, 손절: 81000, 수수료퍼: 0, 목표R: 3 }).경고.some(x => x.includes('1.5%')))
  assert.ok(포지션계산({ 시드: 10000, 위험퍼: 1, 진입: 82000, 손절: 81800, 수수료퍼: 0, 목표R: 3 }).경고.some(x => x.includes('레버리지')))
  assert.ok(포지션계산({ 시드: 10000, 위험퍼: 1, 진입: 82000, 손절: 81900, 수수료퍼: 0, 목표R: 3 }).경고.some(x => x.includes('손절폭')))
  assert.throws(() => 포지션계산({ 시드: 10000, 위험퍼: 1, 진입: 82000, 손절: 82000, 수수료퍼: 0, 목표R: 3 }))
  assert.throws(() => 포지션계산({ 시드: -1, 위험퍼: 1, 진입: 82000, 손절: 81000, 수수료퍼: 0, 목표R: 3 }))
})
